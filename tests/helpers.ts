const fixturesDir = path.join(process.cwd(), "tests", "fixtures");

export function fixturePath(name: string) {
  return path.join(fixturesDir, name);
}

export function fixtureBytes(name: string) {
  return readFileSync(fixturePath(name));
}

export function toArrayBuffer(buffer: Buffer): ArrayBuffer {
  return buffer.buffer.slice(
    buffer.byteOffset,
    buffer.byteOffset + buffer.byteLength
  ) as ArrayBuffer;
}

export async function createTextPdfBytes(text = "Foliant selectable PDF") {
  const doc = await PDFDocument.create();
  const font = await doc.embedFont(StandardFonts.Helvetica);
  const page = doc.addPage([612, 792]);
  const lines = text.split(/\n/);

  lines.forEach((line, index) => {
    page.drawText(line, {
      x: 72,
      y: 720 - index * 24,
      size: 14,
      font,
      color: rgb(0.05, 0.05, 0.05)
    });
  });

  return Buffer.from(await doc.save());
}

export async function createBlankPdfBytes() {
  const doc = await PDFDocument.create();
  doc.addPage([612, 792]);
  return Buffer.from(await doc.save());
}

export function isQpdfAvailable() {
  try {
    execFileSync("qpdf", ["--version"], {stdio: "ignore"});
    return true;
  } catch {
    return false;
  }
}

export function isPdfEncrypted(filePath: string) {
  try {
    execFileSync("qpdf", ["--is-encrypted", filePath], {stdio: "ignore"});
    return true;
  } catch {
    return false;
  }
}

function binaryExists(bin: string, args: string[]) {
  try {
    execFileSync(bin, args, {stdio: "ignore"});
    return true;
  } catch (error) {
    return (error as NodeJS.ErrnoException).code !== "ENOENT";
  }
}

export function isHeicDecoderAvailable() {
  if (process.platform === "darwin") return binaryExists("sips", ["--help"]);
  return binaryExists("magick", ["--version"]) || binaryExists("heif-convert", ["--version"]);
}

export function isLibreOfficeAvailable() {
  const candidates = [
    process.env.LIBREOFFICE_BIN,
    path.join(os.homedir(), ".cache/codex-runtimes/codex-primary-runtime/dependencies/bin/override/soffice"),
    "soffice",
    "libreoffice",
    "/Applications/LibreOffice.app/Contents/MacOS/soffice"
  ].filter(Boolean) as string[];

  return candidates.some((bin) => binaryExists(bin, ["--version"]));
}

function escapeXml(text: string) {
  return text
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

